// ## Transform (runs IN the page)
////////////////

/**
 * Rewrite the source's `<main>` in place into @spell/ui markup and build the contents sidebar.
 * - runs inside the page via `page.evaluate()`, so it MUST be self-contained:  helpers are nested
 * - returns strings:  `main` is the new `<main>`'s inner HTML, `toc` the sidebar's
 * - order matters:  ids and sections first (they read the raw headings), code before cards (cards hold `<pre>`s),
 *   stickies last (they wrap the final headings)
 */
function transform() {
  const main = document.querySelector("main")
  const warnings = []
  const title = document.title
  const description = document.querySelector('meta[name="description"]')?.content ?? ""

  for (const node of main.querySelectorAll("script, style, link")) node.remove()
  removeComments(main)
  moveSectionIds()
  assignIds()
  unwrapSections()
  wrapSections()
  foldCode()
  convertDetails()
  convertCallouts()
  convertTables()
  convertTags()
  convertFlows()
  convertGrids()
  convertSpellNotes()
  convertFilterBar()
  addStickies()
  breakLines(main)
  return { title, description, main: main.innerHTML, toc: buildToc(), warnings }

  ////////////////
  // ## Structure
  ////////////////

  /** Drop HTML comments:  the source's `<!-- ==== -->` rules only separate sections for people editing it. */
  function removeComments(root) {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_COMMENT)
    const comments = []
    while (walker.nextNode()) comments.push(walker.currentNode)
    for (const comment of comments) comment.remove()
  }

  /**
   * A `<section id>` whose heading has no id hands its id to the heading, e.g. CHEATSHEET's `section#packages > h2`.
   * - sections are unwrapped and rebuilt, so this keeps `#packages` links landing on the heading
   * - a section AND heading with ids:  the section id is stashed and put back on the rebuilt section
   */
  function moveSectionIds() {
    for (const section of main.querySelectorAll("section[id]")) {
      const heading = section.querySelector(":scope > h2, :scope > h3")
      if (!heading) {
        warnings.push(`section#${section.id} has no heading:  its id is lost`)
      } else if (!heading.id) {
        heading.id = section.id
      } else {
        heading.dataset.spellSectionId = section.id
      }
      section.removeAttribute("id")
    }
  }

  /** Slug ids for headings that lack one, unique within the page -- the same ids `doc.js` would give. */
  function assignIds() {
    const used = new Set(Array.from(document.querySelectorAll("[id]"), (el) => el.id))
    for (const heading of main.querySelectorAll("h2, h3, h4")) {
      if (heading.id) continue
      const base = slug(labelOf(heading)) || "section"
      let id = base
      for (let n = 2; used.has(id); n++) id = `${base}-${n}`
      used.add(id)
      heading.id = id
    }
  }

  /** Replace every `main > section` (repeatedly, so nested ones too) with its children:  a flat `<main>` again. */
  function unwrapSections() {
    for (let sections; (sections = main.querySelectorAll(":scope > section")).length;) {
      for (const section of sections) section.replaceWith(...section.childNodes)
    }
  }

  /** Wrap each h2 / h3 and what follows it (up to the next h2 / h3) in `section.s2` / `section.s3`, as `doc.js`. */
  function wrapSections() {
    let s2 = null
    let s3 = null
    for (const node of Array.from(main.childNodes)) {
      if (node.nodeType === 1 && node.tagName === "H2") {
        s2 = element("section", { class: "s2" })
        s3 = null
        main.insertBefore(s2, node)
        adoptSectionId(s2, node)
      } else if (node.nodeType === 1 && node.tagName === "H3" && s2) {
        s3 = element("section", { class: "s3" })
        s2.append(s3)
        adoptSectionId(s3, node)
      }
      ;(s3 ?? s2)?.append(node)
    }
  }

  /** Put a stashed source section id (see `moveSectionIds()`) on the rebuilt section. */
  function adoptSectionId(section, heading) {
    if (!heading.dataset.spellSectionId) return
    section.id = heading.dataset.spellSectionId
    delete heading.dataset.spellSectionId
  }

  /** Each section's heading goes in a `ui-sticky`;  RUNTIME sets the h3 stickies' `offset`. */
  function addStickies() {
    for (const heading of main.querySelectorAll("section.s2 > h2, section.s3 > h3")) {
      const sticky = element("ui-sticky", { class: heading.tagName === "H2" ? "spell-h2" : "spell-h3" })
      heading.replaceWith(sticky)
      sticky.append(heading)
    }
  }

  /**
   * Put line breaks between the children of the block-level `ui-*` containers made here.
   * - oxfmt treats unknown elements as inline and glues `><` across lines without them
   * - whitespace is inert there:  accordions / cards lay out element children only
   */
  function breakLines(root) {
    const blocks = "ui-sticky, ui-accordion, ui-content, ui-cards, ui-card, ui-message, ui-table, div.spell-filter"
    for (const block of root.querySelectorAll(blocks)) {
      for (const child of Array.from(block.children)) {
        if (child.previousSibling?.nodeType !== 3) child.before("\n")
      }
      if (block.lastChild?.nodeType === 1) block.append("\n")
    }
  }

  ////////////////
  // ## Code and disclosure
  ////////////////

  /**
   * Every doc-body `<pre>` becomes a `ui-accordion.spell-code` panel;  the `<pre>` node itself moves, untouched.
   * - NOT a bare `<pre>` in a CHEATSHEET card:  card snippets are short and folding them is noise
   * - in a `details`:  its `<summary>` markup is the title (it may hold a link), open if the details was
   * - bare:  titled like `doc.js` does (first `// comment`, else the language, + line count), open at <= 30 lines
   */
  function foldCode() {
    for (const pre of Array.from(main.querySelectorAll("pre"))) {
      if (!pre.isConnected || pre.closest("ui-accordion.spell-code")) continue
      const details = pre.closest("details")
      if (!details && pre.closest("div.card")) continue
      if (details) {
        details.replaceWith(accordion(details, { class: "spell-code", styled: "" }))
        continue
      }
      const lines = pre.textContent.split("\n").length
      const comment = /^\s*\/\/\s*(.+)/.exec(pre.textContent)
      const heading = `${comment ? comment[1].slice(0, 90) : languageOf(pre)} · ${lines} lines`
      const panel = element("ui-accordion", { class: "spell-code", styled: "", ...(lines <= 30 && { open: "0" }) })
      pre.replaceWith(panel)
      panel.append(element("ui-title", {}, [document.createTextNode(heading)]), element("ui-content", {}, [pre]))
    }
  }

  /** Any other `<details>` becomes a styled `ui-accordion`. */
  function convertDetails() {
    for (const details of Array.from(main.querySelectorAll("details"))) {
      details.replaceWith(accordion(details, { styled: "" }))
    }
  }

  /** One-panel `ui-accordion` from a `<details>`:  summary markup => `ui-title`, the rest => `ui-content`. */
  function accordion(details, attributes) {
    const summary = details.querySelector(":scope > summary")
    const panel = element("ui-accordion", { ...attributes, ...(details.open && { open: "0" }) })
    const title = element("ui-title")
    if (summary) {
      title.innerHTML = summary.innerHTML.trim()
      summary.remove()
    } else {
      title.textContent = "Details"
    }
    panel.append(title, element("ui-content", {}, Array.from(details.childNodes)))
    return panel
  }

  ////////////////
  // ## Content blocks
  ////////////////

  /**
   * `div.callout[.good|.bad|.warn]` => `ui-message[state]`.
   * - a first `<p>` holding only a `<b>` becomes the header:  `header="..."` when plain text, else a `ui-header`
   * - trailing `.` / `:` dropped from the header, which is set apart already
   */
  function convertCallouts() {
    const states = { good: "positive", bad: "negative", warn: "warning" }
    for (const callout of Array.from(main.querySelectorAll("div.callout"))) {
      const kind = Object.keys(states).find((name) => callout.classList.contains(name))
      const message = element("ui-message", { state: states[kind] ?? "info" })
      const first = callout.firstElementChild
      const bold = first?.tagName === "P" && onlyChild(first)
      if (bold?.tagName === "B") {
        if (bold.children.length) {
          const header = element("ui-header")
          header.innerHTML = bold.innerHTML.trim().replace(/[.:]$/, "")
          message.append(header)
        } else {
          message.setAttribute("header", bold.textContent.replace(/\s+/g, " ").trim().replace(/[.:]$/, ""))
        }
        first.remove()
      }
      message.append(...callout.childNodes)
      callout.replaceWith(message)
    }
  }

  /**
   * Every `<table>` goes in a `ui-table celled compact striped unstackable` (replacing any `div.table-wrap`).
   * - cell classes gain Fomantic words, old ones kept:  `.num` => `right aligned`, `.yes` / `.no` / `.meh` =>
   *   `positive` / `negative` / `warning`
   */
  function convertTables() {
    const words = { num: ["right", "aligned"], yes: ["positive"], no: ["negative"], meh: ["warning"] }
    for (const table of Array.from(main.querySelectorAll("table"))) {
      const wrapper = table.parentElement.matches("div.table-wrap") ? table.parentElement : table
      const uiTable = element("ui-table", { celled: "", compact: "", striped: "", unstackable: "" })
      wrapper.replaceWith(uiTable)
      uiTable.append(table)
      for (const cell of table.querySelectorAll("td, th")) {
        for (const [name, added] of Object.entries(words)) {
          if (cell.classList.contains(name)) cell.classList.add(...added)
        }
      }
    }
  }

  /** `span.tag` badges => `ui-label size=mini`, coloured as CHEATSHEET coloured them (new / gone / changed). */
  function convertTags() {
    const colors = { new: "green", gone: "red", changed: "orange", "spell-legend": "orange" }
    for (const tag of Array.from(main.querySelectorAll("span.tag"))) {
      const kind = Object.keys(colors).find((name) => tag.classList.contains(name))
      const label = element("ui-label", { size: "mini", ...(kind && { color: colors[kind] }) })
      label.innerHTML = tag.innerHTML
      tag.replaceWith(label)
    }
  }

  /**
   * `div.flow` steps (`<div><b>Name</b>rest</div>`) => `ui-cards.spell-flow` of header + description cards.
   * - `spell-flow`:  spell-doc.css lays them out small and many to a row, as the source's boxes were
   */
  function convertFlows() {
    for (const flow of Array.from(main.querySelectorAll("div.flow"))) {
      const cards = element("ui-cards", { class: "spell-flow", stackable: "" })
      for (const step of Array.from(flow.children)) {
        const content = element("ui-content")
        const name = firstNonBlank(step)
        if (name?.nodeType === 1 && name.tagName === "B") {
          const header = element("ui-header")
          header.innerHTML = name.innerHTML
          content.append(header)
          name.remove()
        }
        const text = element("ui-description")
        text.innerHTML = step.innerHTML.trim()
        content.append(text)
        cards.append(element("ui-card", {}, [content]))
      }
      flow.replaceWith(cards)
    }
  }

  /**
   * CHEATSHEET's `div.grid > div.card` => `ui-cards.spell-grid stackable > ui-card > ui-content`, card markup kept.
   * - no `fluid`:  spell-doc.css lays out the grid (`spell-grid`), columns as the source's `auto-fill` did
   * - a card spanning the grid (`style="grid-column: 1 / -1"`) gets `data-spell-wide` for spell-doc.css:
   *   a `ui-card` host is `display: contents`, so a grid style on it does nothing
   */
  function convertGrids() {
    for (const grid of Array.from(main.querySelectorAll("div.grid"))) {
      const cards = element("ui-cards", { class: "spell-grid", stackable: "" })
      for (const card of Array.from(grid.children)) {
        if (!card.matches("div.card")) warnings.push(`div.grid holds a <${card.tagName.toLowerCase()}>, not a card`)
        const wide = /grid-column/.test(card.getAttribute("style") ?? "")
        const uiCard = element("ui-card", { ...(wide && { "data-spell-wide": "" }) })
        uiCard.append(element("ui-content", {}, Array.from(card.childNodes)))
        cards.append(uiCard)
      }
      grid.replaceWith(cards)
    }
  }

  /** CHEATSHEET's `div.spell` notes => small warning `ui-message`s. */
  function convertSpellNotes() {
    for (const note of Array.from(main.querySelectorAll("div.spell"))) {
      note.replaceWith(element("ui-message", { state: "warning", size: "small" }, Array.from(note.childNodes)))
    }
  }

  /**
   * CHEATSHEET's `.bar` (filter input + section nav) => `div.spell-filter` holding a `ui-input[data-spell-filter]`.
   * - the nav goes:  the contents sidebar replaces it
   * - its "No card matches." line stays, `hidden`, as `p.spell-filter-empty` for RUNTIME to show
   */
  function convertFilterBar() {
    for (const bar of Array.from(main.querySelectorAll("div.bar"))) {
      const input = bar.querySelector("input")
      const uiInput = element("ui-input", {
        icon: "search",
        // a search field, as the source's:  the browser's clear button, Escape clears
        type: input?.getAttribute("type") ?? "search",
        ...(input?.id && { id: input.id }),
        placeholder: input?.placeholder ?? "Filter",
        "aria-label": input?.getAttribute("aria-label") ?? "Filter",
        "data-spell-filter": ""
      })
      bar.replaceWith(element("div", { class: "spell-filter" }, [uiInput]))
    }
    for (const empty of main.querySelectorAll("p.empty")) {
      empty.className = "spell-filter-empty"
      empty.hidden = true
    }
  }

  ////////////////
  // ## Contents sidebar
  ////////////////

  /**
   * The contents sidebar's markup, from the h2 / h3 / h4 ids in document order.
   * - one accordion pair per h2;  inside, runs of leaf h3s (and h4s straight under the h2) share a `ui-menu`,
   *   an h3 with h4s gets a nested one-pair accordion
   * - every link carries `data-target` for RUNTIME's scroll-follow
   */
  function buildToc() {
    const groups = []
    const orphans = []
    for (const heading of main.querySelectorAll("h2[id], h3[id], h4[id]")) {
      const group = groups.at(-1)
      if (heading.tagName === "H2") groups.push({ heading, children: [] })
      else if (heading.tagName === "H3") (group?.children ?? orphans).push({ heading, children: [] })
      else {
        const parent = group?.children.at(-1)
        if (parent?.heading.tagName === "H3") parent.children.push({ heading, children: [] })
        else (group?.children ?? orphans).push({ heading, children: [] })
      }
    }
    if (orphans.length)
      warnings.push(`${orphans.length} heading(s) before the first h2 sit above the contents accordion`)

    const pairs = groups.map(
      (group) => `<ui-title>${link(group.heading)}</ui-title>\n<ui-content>\n${nodes(group.children)}\n</ui-content>`
    )
    return `<ui-sticky offset="0">
<div class="spell-toc-inner">
<div class="spell-toc-head">
<b>Contents</b>
<ui-buttons size="mini" basic>
<ui-button data-toc="expand">expand</ui-button>
<ui-button data-toc="collapse">collapse</ui-button>
<ui-button data-toc="code">code</ui-button>
</ui-buttons>
</div>
${nodes(orphans)}
<ui-accordion class="spell-toc" exclusive="no">
${pairs.join("\n")}
</ui-accordion>
</div>
</ui-sticky>`
  }

  /** Menus for runs of leaf nodes, a nested accordion for each node with children, in order. */
  function nodes(list) {
    const out = []
    let run = []
    for (const node of list) {
      if (!node.children.length) {
        run.push(node)
        continue
      }
      flush()
      out.push(`<ui-accordion exclusive="no">
<ui-title>${link(node.heading)}</ui-title>
<ui-content>\n${nodes(node.children)}\n</ui-content>
</ui-accordion>`)
    }
    flush()
    return out.join("\n")

    /** Emit the pending run of leaves as one vertical text menu. */
    function flush() {
      if (!run.length) return
      const items = run.map(
        ({ heading }) =>
          `<ui-item href="#${attr(heading.id)}" data-target="${attr(heading.id)}">${text(labelOf(heading))}</ui-item>`
      )
      out.push(`<ui-menu vertical text fluid>\n${items.join("\n")}\n</ui-menu>`)
      run = []
    }
  }

  /** A title's link to a heading. */
  function link(heading) {
    return `<a href="#${attr(heading.id)}" data-target="${attr(heading.id)}">${text(labelOf(heading))}</a>`
  }

  ////////////////
  // ## Helpers
  ////////////////

  /** New element with attributes (`""` => boolean attribute) and children. */
  function element(tag, attributes = {}, children = []) {
    const el = document.createElement(tag)
    for (const [name, value] of Object.entries(attributes)) el.setAttribute(name, value)
    el.append(...children)
    return el
  }

  /** The only element child of `parent`, if nothing but whitespace sits beside it. */
  function onlyChild(parent) {
    const nodes = Array.from(parent.childNodes).filter((node) => node.nodeType !== 3 || node.textContent.trim())
    return nodes.length === 1 && nodes[0].nodeType === 1 ? nodes[0] : null
  }

  /** First child node that isn't blank text. */
  function firstNonBlank(parent) {
    return Array.from(parent.childNodes).find((node) => node.nodeType !== 3 || node.textContent.trim())
  }

  /** A heading's text without its badges, whitespace collapsed -- as `doc.js` `labelOf()`. */
  function labelOf(heading) {
    const clone = heading.cloneNode(true)
    for (const badge of clone.querySelectorAll(".tag, ui-label")) badge.remove()
    return clone.textContent.replace(/\s+/g, " ").trim()
  }

  /** Slug for an id -- MUST match `doc.js` `slug()`, so generated ids agree between the two pages. */
  function slug(label) {
    return label
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-|-$/g, "")
      .slice(0, 48)
  }

  /** Language name from a `<pre><code class="language-x">`, as `doc.js` `languageOf()`. */
  function languageOf(pre) {
    const match = /language-(\w+)/.exec(pre.querySelector("code")?.className ?? "")
    return { ts: "TypeScript", tsx: "TSX", js: "JavaScript", sh: "Shell", json: "JSON" }[match?.[1]] ?? "Code"
  }

  /** Escape for text content. */
  function text(value) {
    return value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
  }

  /** Escape for a double-quoted attribute value. */
  function attr(value) {
    return text(value).replace(/"/g, "&quot;")
  }
}

