import { existsSync, readdirSync, readFileSync } from "node:fs"
import { join } from "node:path"
import { fileURLToPath } from "node:url"

import { parseHTML } from "linkedom"

import { PageOutline } from "$/ui/docs-components/ui-docs-search/PageOutline"
import type {
  SiteAttribute,
  SiteDataFile,
  SiteFamily,
  SiteNav,
  SiteSearchFile,
  SiteSearchPage,
  SiteTag
} from "$/ui/docs-components/docs-components.types"
import { Definitions } from "$/epics/definitions"
import type { EpicTag, EpicVocabulary } from "$/epics/definitions"

/****************
 * ### `EpicUISite`
 * The data of Epic UI, the docs set of the `<epic-*>` elements (`packages/epic-components/`, served at `/epic-ui/`;
 * epic `epic-workflow` P10):  what its side column, search and look controls read, in Spell UI's shapes, since its
 * pages load Spell UI's site bundle.
 * - `_data/components.json` (`SiteDataFile`):  one entry per element, from the pack's own definitions
 *   (`Definitions.all`:  each vocabulary as data), filed under the groups of the set's hand-kept `_data/pages.json`;
 *   plus the set's own side-column links (`nav`)
 *   - a new element shows up by itself:  under "Other" until `pages.json` files it, `planned` until its page exists
 *   - the elements drawn only inside others' shadow roots (`pages.json` `drawnOnly`) are never listed
 * - `_data/search.json` (`SiteSearchFile`):  every page's title and sections, read from the page files by Spell UI's
 *   own rules (`PageOutline`), for the side column's search
 * - Written by `yarn site:data` (`scripts/site-data.ts`);  `EpicUISite.test.ts` fails while they're stale:  rerun
 *   after adding or changing an element, or a page's sections.
 * - Node only (`node:fs`, linkedom);  deterministic:  no dates.
 ****************/
export class EpicUISite {
  /** the set's folder, `packages/epic-components/` */
  readonly folder: string

  constructor(folder = SET_FOLDER) {
    this.folder = folder
  }

  /** `components.json`, as data. */
  data(): SiteDataFile {
    const pages = this.pages()
    const filed = new Map(pages.groups.flatMap((group) => group.tags.map((tag) => [tag, group.id] as const)))
    const listed = Definitions.tags.filter((tag) => !pages.drawnOnly.includes(tag))
    const others = listed.filter((tag) => !filed.has(tag))
    const groups = others.length ? [...pages.groups, { id: OTHER.id, title: OTHER.title, tags: others }] : pages.groups
    const tags = listed
      .map((tag) => this.tag(tag, filed.get(tag) ?? OTHER.id))
      .sort((a, b) => a.name.localeCompare(b.name))
    return {
      $comment: `GENERATED by \`yarn site:data\` (packages/epics, scripts/site-data.ts, src/site/EpicUISite.ts) from the epics pack's definitions and ${PAGES_FILE} -- do not edit.  Shape:  \`SiteDataFile\` in packages/ui/src/docs-components/docs-components.types.ts.`,
      version: 1,
      topics: groups.map(({ id, title }) => ({ id, title })),
      components: tags,
      docs: [],
      families: Object.fromEntries(tags.map((tag) => [tag.tag, this.family(tag)])),
      foundation: [],
      themes: [],
      nav: pages.nav
    }
  }

  /** `search.json`, as data:  the home first, then each element page A-Z. */
  search(): SiteSearchFile {
    return {
      $comment: `GENERATED by \`yarn site:data\` (packages/epics, scripts/site-data.ts, src/site/EpicUISite.ts) from the set's pages -- do not edit.  Shape:  \`SiteSearchFile\` in packages/ui/src/docs-components/docs-components.types.ts.`,
      pages: this.pageFiles().map((path) => EpicUISite.searchPage(path, readFileSync(join(this.folder, path), "utf8")))
    }
  }

  /** The two files' text, by name in `_data/`:  2-space JSON. */
  files(): Record<string, string> {
    return {
      [COMPONENTS_FILE]: `${JSON.stringify(this.data(), null, 2)}\n`,
      [SEARCH_FILE]: `${JSON.stringify(this.search(), null, 2)}\n`
    }
  }

  /** Every page, relative to the set's folder:  `index.html`, then `elements/*.html` A-Z. */
  pageFiles(): string[] {
    const elements = join(this.folder, ELEMENTS)
    const files = existsSync(elements) ? readdirSync(elements).filter((file) => file.endsWith(".html")) : []
    return [
      ...(existsSync(join(this.folder, HOME)) ? [HOME] : []),
      ...files.sort().map((file) => `${ELEMENTS}/${file}`)
    ]
  }

  /** The hand-kept facts, `_data/pages.json`. */
  private pages(): EpicUIPages {
    return JSON.parse(readFileSync(join(this.folder, DATA, PAGES_FILE), "utf8")) as EpicUIPages
  }

  /** `tag`'s entry:  its vocabulary, as Spell UI's site data has a tag's. */
  private tag(tag: EpicTag, group: string): SiteTag {
    const vocabulary: EpicVocabulary = Definitions.all[tag]
    return {
      tag,
      name: tag,
      folder: tag,
      mainTag: tag,
      main: true,
      page: true,
      href: `${ELEMENTS}/${tag}.html`,
      topics: [group],
      aka: [...(vocabulary.aka ?? [])],
      ...(vocabulary.description && { description: vocabulary.description }),
      noun: vocabulary.noun ?? tag.replace(/^epic-/, ""),
      attributes: vocabulary.attributes.map((spec) => EpicUISite.attribute(spec)),
      slots: vocabulary.slots.map(({ name, description }) => ({ name, description })),
      events: vocabulary.events.map(({ name, detail, cancelable, description }) => ({
        name,
        detail,
        ...(cancelable && { cancelable }),
        description
      })),
      parts: vocabulary.parts.map(({ name, description }) => ({ name, description })),
      states: vocabulary.states.map(({ name, description }) => ({ name, description })),
      texts: vocabulary.texts.map(({ key, text, description }) => ({ key, text, ...(description && { description }) }))
    }
  }

  /** `tag`'s family:  the element alone, its page's title and summary;  `planned` while it has no page. */
  private family(tag: SiteTag): SiteFamily {
    const file = join(this.folder, tag.href!)
    const summary = existsSync(file) ? EpicUISite.summaryOf(readFileSync(file, "utf8")) : undefined
    return {
      folder: tag.tag,
      mainTag: tag.tag,
      title: `<${tag.tag}>`,
      summary: summary ?? tag.description ?? "",
      status: existsSync(file) ? "done" : "planned",
      docs: false,
      tags: [tag.tag],
      tokens: []
    }
  }

  /** One attribute, as Spell UI's site data has it. */
  private static attribute(spec: EpicVocabulary["attributes"][number]): SiteAttribute {
    return {
      name: spec.name,
      kind: spec.kind,
      ...(Array.isArray(spec.values) && { values: [...spec.values] }),
      ...(typeof spec.values === "string" && { valueSet: spec.values }),
      ...(spec.default !== undefined && { default: spec.default }),
      ...(spec.aliases && { aliases: [...spec.aliases] }),
      ...(spec.property && { property: spec.property }),
      ...(spec.reflect === false && { reflect: false }),
      description: spec.description
    }
  }

  /** A page's search entry:  its title, summary and sections, as Spell UI's search file has a page's. */
  static searchPage(path: string, html: string): SiteSearchPage {
    const { document } = parseHTML(html)
    const main = document.querySelector("main#main") ?? document.body
    const { sections, tabs } = PageOutline.sections(main as unknown as Element)
    const title = main.getAttribute("data-toc-header")?.trim() || document.querySelector("title")?.textContent?.trim()
    const summary = EpicUISite.summaryOf(html)
    const tag = path.startsWith(`${ELEMENTS}/`) ? path.slice(ELEMENTS.length + 1).replace(/\.html$/, "") : undefined
    return {
      path,
      title: title ?? path,
      ...(summary && { summary }),
      ...(tag && { tag }),
      ...(Object.keys(tabs).length && { tabs }),
      sections
    }
  }

  /** A page's `<meta name="description">`, on one line;  `undefined` without one. */
  private static summaryOf(html: string): string | undefined {
    const { document } = parseHTML(html)
    const content = document.querySelector('meta[name="description"]')?.getAttribute("content")
    return content?.replace(/\s+/g, " ").trim() || undefined
  }
}

/**
 * The set's hand-kept facts, `_data/pages.json`.
 * - `groups`:  the side column's groups, in order, each the tags filed under it
 * - `drawnOnly`:  elements drawn only inside other elements' shadow roots, never written in a doc:  no page
 * - `nav`:  the side column's own links and band titles (`SiteNav`)
 */
export type EpicUIPages = {
  readonly groups: readonly { readonly id: string; readonly title: string; readonly tags: readonly string[] }[]
  readonly drawnOnly: readonly string[]
  readonly nav: SiteNav
}

/** The set's folder:  `packages/epic-components/`, beside this package. */
const SET_FOLDER = fileURLToPath(new URL("../../../epic-components/", import.meta.url))

/** The set's home page. */
const HOME = "index.html"

/** The element pages' folder. */
const ELEMENTS = "elements"

/** The data folder, and its files. */
const DATA = "_data"
const PAGES_FILE = "pages.json"
const COMPONENTS_FILE = "components.json"
const SEARCH_FILE = "search.json"

/** The group of an element `pages.json` doesn't file yet. */
const OTHER = { id: "other", title: "Other" } as const
