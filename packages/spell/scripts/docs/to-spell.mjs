/**
 * Compare an output with its source, both loaded static.
 * - problems:  what broke a promise the output makes (see the file header)
 * - counts:  what the output holds, for the log
 */
async function check(sourcePath, outputPath) {
  if (!existsSync(outputPath)) return { problems: [`${outputPath} doesn't exist`], counts: {} }
  const sourcePage = await openStatic(sourcePath)
  const before = await sourcePage.evaluate(facts, { dropped: ".bar nav" })
  await sourcePage.context().close()
  const outputPage = await openStatic(outputPath)
  const after = await outputPage.evaluate(facts, { dropped: "", unmapped: UNMAPPED })
  await outputPage.context().close()

  const problems = []
  const html = readFileSync(outputPath, "utf8")
  if (!/^<!doctype html>\s*<html[^>]*>\s*<!-- GENERATED by yarn docs:update from /i.test(html)) {
    problems.push("missing the GENERATED header comment")
  }
  if (before.pres.length !== after.pres.length) {
    problems.push(`<pre> count ${before.pres.length} => ${after.pres.length}`)
  }
  before.pres.forEach((pre, index) => {
    if (after.pres[index] !== pre)
      problems.push(`<pre> #${index + 1} text changed:  ${JSON.stringify(pre.slice(0, 60))}`)
  })
  for (const id of before.ids) if (!after.ids.includes(id)) problems.push(`id lost:  #${id}`)
  for (const id of after.duplicateIds) problems.push(`duplicate id in page:  #${id}`)
  const remaining = [...after.links]
  for (const pair of before.links) {
    const index = remaining.indexOf(pair)
    if (index < 0) problems.push(`link lost:  ${pair}`)
    else remaining.splice(index, 1)
  }
  if (after.targets.length !== after.headingIds.length) {
    problems.push(`${after.headingIds.length} headings but ${after.targets.length} contents links`)
  }
  for (const target of after.targets) {
    if (!after.headingIds.includes(target)) problems.push(`contents link to no heading:  #${target}`)
  }
  for (const [selector, count] of Object.entries(after.leftovers)) {
    if (count) problems.push(`${count} unmapped ${selector}`)
  }
  if (after.counts.code !== after.counts.bodyPres) {
    problems.push(`${after.counts.bodyPres} <pre> outside cards but ${after.counts.code} code panels`)
  }
  if (after.counts.cardCode) problems.push(`${after.counts.cardCode} code panel(s) inside a ui-card`)

  const counts = {
    headings: after.headingIds.length,
    "contents links": after.targets.length,
    "code panels": after.counts.code,
    pre: after.pres.length,
    messages: after.counts.messages,
    tables: after.counts.tables,
    labels: after.counts.labels,
    cards: after.counts.cards,
    stickies: after.counts.stickies,
    accordions: after.counts.accordions,
    links: after.links.length
  }
  return { problems, counts }
}

/**
 * What `check()` compares, read IN the page from its static DOM.
 * - `dropped`:  a selector for source parts the conversion deliberately removes (their links / ids don't count)
 * - `unmapped`:  selectors that must match nothing
 */
function facts({ dropped, unmapped = [] }) {
  const main = document.querySelector("main")
  const keep = (el) => !dropped || !el.closest(dropped)
  const allIds = Array.from(document.querySelectorAll("[id]"), (el) => el.id)
  return {
    pres: Array.from(main.querySelectorAll("pre"), (pre) => pre.textContent),
    ids: Array.from(main.querySelectorAll("[id]"))
      .filter(keep)
      .map((el) => el.id),
    duplicateIds: [...new Set(allIds.filter((id, index) => allIds.indexOf(id) !== index))],
    headingIds: Array.from(main.querySelectorAll("h2[id], h3[id], h4[id]"), (el) => el.id),
    links: Array.from(main.querySelectorAll("a[href]"))
      .filter(keep)
      .map((a) => `${a.getAttribute("href")} -> ${a.getAttribute("target") ?? "(no target)"}`),
    targets: Array.from(document.querySelectorAll("#spell-toc [data-target]"), (el) => el.dataset.target),
    leftovers: Object.fromEntries(unmapped.map((selector) => [selector, main.querySelectorAll(selector).length])),
    counts: {
      code: main.querySelectorAll("ui-accordion.spell-code").length,
      bodyPres: Array.from(main.querySelectorAll("pre")).filter((pre) => !pre.closest("ui-card")).length,
      cardCode: main.querySelectorAll("ui-card ui-accordion.spell-code").length,
      messages: main.querySelectorAll("ui-message").length,
      tables: main.querySelectorAll("ui-table").length,
      labels: main.querySelectorAll("ui-label").length,
      cards: main.querySelectorAll("ui-card").length,
      stickies: main.querySelectorAll("ui-sticky").length,
      accordions: document.querySelectorAll("ui-accordion").length
    }
  }
}
