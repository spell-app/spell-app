/**
 * `yarn site:data [--check]` (in `packages/brand`):  the data of the brand's docs set, `docs/__data/`, served at
 * `/components/brand/__data/` with the set's pages (epic `people-and-orgs` P18).
 * - `components.json` (`SiteDataFile`):  every `<brand-*>` tag, from its vocabulary and sheet, by Spell UI's own
 *   builder (`packages/ui/tools/SiteDataBuilder.ts`), then made the set's:
 *   - each tag's page is `<tag>.html`, beside the data's folder (the set's pages are ONE flat folder)
 *   - its topics are the set's groups, from `pages.json` (the side column's groups, as Epic UI's)
 *   - `nav`:  the side column's own links and band titles, from `pages.json`
 * - `pages.json`:  HAND-KEPT.  Spell UI's per-family facts (title, summary, status;  a new family is seeded here, once),
 *   plus the set's own `groups` and `nav`, which this script keeps.
 * - `search.json` (`SiteSearchFile`):  every page's title and sections, read from the pages' markup by Spell UI's rules
 *   (`SiteSearchBuilder.page()`);  an element's page names its tag.
 * - `custom-elements.json` (`package.json`'s `customElements`) and `html-custom-data.json` (VS Code's
 *   `html.customData`, loaded by the repo's `.vscode/settings.json`):  the editors' element descriptions, by Spell UI's
 *   `ElementManifests`.
 * - `--check`:  writes nothing;  exits 1 while any file is stale (`spell dev pack check brand` runs it).
 * - `spell dev pack build brand` runs it after the pack.  Rerun it after changing a vocabulary, a sheet's tokens or a
 *   page's sections, and commit what it writes.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"

import type { SiteDataFile, SiteNav, SitePagesFile, SiteSearchFile } from "$/ui/docs-components/docs-components.types"
import { ElementManifests } from "$/ui/tools/ElementManifests"
import { SiteDataBuilder } from "$/ui/tools/SiteDataBuilder"
import { SiteSearchBuilder } from "$/ui/tools/SiteSearchBuilder"

/** `packages/brand/`. */
const BRAND = path.resolve(import.meta.dirname, "..")

/** The set's pages, `docs/`, and its data, `docs/__data/`. */
const DOCS = path.join(BRAND, "docs")
const DATA = path.join(DOCS, "__data")

/** The set's home;  every other page in `docs/` is an element's, named for its tag. */
const HOME = "index.html"

/** `pages.json`'s own comment:  what it holds, and who reads it. */
const PAGES_COMMENT =
  "HAND-KEPT facts of the brand's docs set, read by `yarn site:data` in packages/brand (scripts/site-data.ts), which " +
  "writes components.json and search.json beside this.  `families`:  Spell UI's per-family facts (title, summary, " +
  "status ...;  `SitePagesFile` in packages/ui/src/docs-components/docs-components.types.ts), a new family seeded " +
  "here once.  `groups`:  the side column's groups, in order;  a tag no group names shows under Other.  `nav`:  the " +
  "side column's own links (`file` relative to the set's root, `/components/brand/`) and band titles (`SiteNav`)."

/** Where a tag no group names is filed. */
const OTHER = { id: "other", title: "Other" }

const isCheck = process.argv.includes("--check")
const builder = new SiteDataBuilder({ components: path.join(BRAND, "components"), docs: false, data: DATA })
const own = readOwnFacts()
const { data, pages } = await builder.build()
const setData = forTheSet(data, own)
const files = new Map<string, string>([
  [builder.dataFile, SiteDataBuilder.stringify(setData)],
  [builder.pagesFile, SiteDataBuilder.stringify(pagesFile(pages, own))],
  [path.join(DATA, "search.json"), SiteDataBuilder.stringify(search())],
  ...new ElementManifests({
    data: setData,
    packageFolder: BRAND,
    componentsPath: "components",
    readme:
      "Spell's brand elements (`brand-*`), a component pack on Spell UI.  Generated by `yarn site:data` -- do not edit."
  }).outputs(DATA)
])

let stale = 0
for (const [file, text] of files) {
  if (readOrEmpty(file) === text) continue
  stale++
  if (isCheck) console.error(`stale:  ${path.relative(process.cwd(), file)}  (yarn site:data, in packages/brand)`)
  else writeFileSync(file, text)
}
console.log(
  `brand site data:  ${setData.components.length} tags in ${Object.keys(setData.families).length} families;  ` +
    (stale ? `${stale} file${stale === 1 ? "" : "s"} ${isCheck ? "stale" : "written"}` : "current")
)
if (isCheck && stale) process.exit(1)

/** Spell UI's data, made the set's:  flat page links, the set's groups as topics, its own side-column links. */
function forTheSet(data: SiteDataFile, { groups, nav }: OwnFacts): SiteDataFile {
  const groupOf = new Map(groups.flatMap((group) => group.tags.map((tag) => [tag, group.id] as const)))
  const others = data.components.filter((tag) => !groupOf.has(tag.tag)).map((tag) => tag.tag)
  const topics = [...groups, ...(others.length ? [{ ...OTHER, tags: others }] : [])]
  return {
    ...data,
    $comment:
      "GENERATED by `yarn site:data` (packages/brand, scripts/site-data.ts) -- do not edit.  Shape:  `SiteDataFile` in " +
      "packages/ui/src/docs-components/docs-components.types.ts;  hand-kept facts:  pages.json beside this.",
    topics: topics.map(({ id, title }) => ({ id, title })),
    components: data.components.map((tag) => ({
      ...tag,
      topics: [groupOf.get(tag.tag) ?? OTHER.id],
      ...(tag.href && { href: tag.href.replace(/^components\//, "") })
    })),
    nav
  }
}

/** `pages.json` as kept:  Spell UI's facts (a new family seeded), then the set's own. */
function pagesFile(pages: SitePagesFile, own: OwnFacts): SitePagesFile & OwnFacts {
  return { ...pages, $comment: PAGES_COMMENT, ...own }
}

/** `search.json`:  the home first, then each element page A-Z, each naming its tag. */
function search(): SiteSearchFile {
  const pages = existsSync(DOCS) ? readdirSync(DOCS).filter((file) => file.endsWith(".html") && file !== HOME) : []
  const files = [...(existsSync(path.join(DOCS, HOME)) ? [HOME] : []), ...pages.sort()]
  return {
    $comment:
      "GENERATED by `yarn site:data` (packages/brand, scripts/site-data.ts) from the set's pages -- do not edit.  " +
      "Shape:  `SiteSearchFile` in packages/ui/src/docs-components/docs-components.types.ts.",
    pages: files.map((file) => {
      const page = SiteSearchBuilder.page(file, readFileSync(path.join(DOCS, file), "utf8"))
      return file === HOME ? page : { ...page, tag: file.replace(/\.html$/, "") }
    })
  }
}

/** The set's own hand-kept facts in `pages.json`, which Spell UI's builder doesn't keep:  `groups` and `nav`. */
function readOwnFacts(): OwnFacts {
  const file = JSON.parse(readFileSync(path.join(DATA, "pages.json"), "utf8")) as Partial<OwnFacts>
  if (!file.groups || !file.nav) {
    throw new TypeError("site-data:  docs/__data/pages.json has no `groups` or `nav`;  add them (see Epic UI's)")
  }
  return { groups: file.groups, nav: file.nav }
}

/** `file`'s text;  `""` when it doesn't exist yet. */
function readOrEmpty(file: string): string {
  try {
    return readFileSync(file, "utf8")
  } catch {
    return ""
  }
}

/**
 * The set's own facts in `pages.json`, beside Spell UI's (`SitePagesFile`).
 * - `groups`:  the side column's groups, in order, each the tags filed under it;  an unfiled tag shows under Other
 * - `nav`:  the side column's own links (`file` relative to the set's root, `/components/brand/`) and band titles
 */
type OwnFacts = {
  readonly groups: readonly { readonly id: string; readonly title: string; readonly tags: readonly string[] }[]
  readonly nav: SiteNav
}
