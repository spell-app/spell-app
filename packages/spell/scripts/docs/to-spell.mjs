/**
 * Convert hand-written HTML docs into `<name>.spell.html`, rendered with @spell/ui widgets -- see `yarn docs:update`.
 * Usage:  node scripts/docs/to-spell.mjs [--check] docs/<folder>/<doc>.html [...]
 * - loads each source in Chromium with scripts OFF, so `doc.js` can't have touched the DOM we read
 * - maps the source's semantic markup onto `ui-*` elements, builds the contents sidebar from the headings,
 *   writes the page skeleton around them, formats with oxfmt
 * - then checks the output against the source (exit 1 on any problem):  `<pre>` text identical, ids and
 *   `a[href]` + `target` pairs kept, one contents link per heading, no source class left unmapped
 * - `--check`:  only check existing outputs, write nothing
 */
import { execFileSync } from "node:child_process"
import { existsSync, readFileSync, writeFileSync } from "node:fs"
import { basename, dirname, join, relative, resolve } from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"

import { chromium } from "playwright"

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "../..")
const OXFMT = join(REPO, "node_modules/.bin/oxfmt")

/** Source classes that MUST have been mapped:  any left in an output means the converter missed one. */
const UNMAPPED = [
  "div.callout",
  "div.table-wrap",
  "span.tag",
  "div.flow",
  "details.code",
  "div.card",
  "div.grid",
  "div.spell",
  "div.bar"
]

const args = process.argv.slice(2)
const checkOnly = args.includes("--check")
const sources = args.filter((arg) => arg !== "--check")
if (!sources.length) {
  console.error("usage:  node scripts/docs/to-spell.mjs [--check] docs/<folder>/<doc>.html [...]")
  process.exit(2)
}

const browser = await chromium.launch()
let failed = false
try {
  for (const source of sources) {
    const sourcePath = resolve(source)
    const outputPath = sourcePath.replace(/\.html$/, ".spell.html")
    if (!checkOnly) {
      writeFileSync(outputPath, await convert(sourcePath))
      execFileSync(OXFMT, [outputPath], { stdio: "inherit" })
    }
    const { problems, counts } = await check(sourcePath, outputPath)
    const summary = Object.entries(counts)
      .map(([name, count]) => `${name} ${count}`)
      .join(", ")
    console.log(`${relative(REPO, outputPath)}:  ${summary}`)
    for (const problem of problems) console.error(`  PROBLEM:  ${problem}`)
    if (problems.length) failed = true
  }
} finally {
  await browser.close()
}
process.exit(failed ? 1 : 0)

