// ## Convert
////////////////

/** The whole `.spell.html` for one source:  skeleton + converted `<main>` + contents sidebar. */
async function convert(sourcePath) {
  const page = await openStatic(sourcePath)
  const converted = await page.evaluate(transform)
  const { title, description, warnings } = converted
  const [main, toc] = [converted.main, converted.toc].map(bareBooleans)
  await page.context().close()
  for (const warning of warnings) console.warn(`  ${basename(sourcePath)}:  ${warning}`)

  const assets = relative(dirname(sourcePath), join(docsRoot(sourcePath), "_assets"))
    .split("\\")
    .join("/")
  return `<!doctype html>
<html lang="en">
  <!-- GENERATED by yarn docs:update from ${basename(sourcePath)} -- edit the source, not this file -->
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${escapeText(title)}</title>
    <meta name="description" content="${escapeAttribute(description)}" />
    <link rel="stylesheet" href="${assets}/spell-doc.css" />
  </head>
  <body class="spell-doc-page">
    <div class="spell-doc">
      <main class="spell-doc-main">${main}</main>
      <aside class="spell-doc-toc" id="spell-toc" aria-label="Contents">${toc}</aside>
    </div>
    <ui-button class="spell-toc-open" size="small">Contents</ui-button>
    <script src="https://cdnjs.cloudflare.com/ajax/libs/highlight.js/11.9.0/highlight.min.js"></script>
    <script src="${assets}/spell-ui.js"></script>
  </body>
</html>
`
}

/**
 * Open a doc from disk with its scripts OFF and nothing fetched but local files.
 * - so what we read is the static markup, never what `doc.js` or a page script made of it
 * - `page.evaluate()` still works with page JS disabled
 */
async function openStatic(path) {
  const context = await browser.newContext({ javaScriptEnabled: false })
  const page = await context.newPage()
  await page.route(/^(?!file:)/, (route) => route.abort())
  await page.goto(pathToFileURL(path).href)
  return page
}

/** The `docs/` folder holding a source:  the nearest ancestor with an `_assets/` folder. */
function docsRoot(sourcePath) {
  for (let dir = dirname(sourcePath); dir !== dirname(dir); dir = dirname(dir)) {
    if (existsSync(join(dir, "_assets"))) return dir
  }
  throw new Error(`no _assets/ folder above ${sourcePath}`)
}

/**
 * `styled=""` => `styled` in start tags, as a person would write it.
 * - safe:  serialized text escapes `<`, so every raw `<...>` is a tag, and a quoted `=""` inside a value is `&quot;`
 */
function bareBooleans(html) {
  return html.replace(/<[a-z][\w-]*\s[^<>]*>/g, (tag) => tag.replace(/ ([\w-]+)=""/g, " $1"))
}

/** Escape for text content. */
function escapeText(text) {
  return text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
}

/** Escape for a double-quoted attribute value. */
function escapeAttribute(text) {
  return escapeText(text).replace(/"/g, "&quot;")
}

